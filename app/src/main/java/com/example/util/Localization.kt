package com.example.util

object Localization {

    fun get(key: String, language: AppLanguage): String {
        val map = when (language) {
            AppLanguage.GUJARATI -> gujaratiMap
            AppLanguage.HINDI -> hindiMap
            AppLanguage.ENGLISH -> englishMap
            AppLanguage.MARATHI -> marathiMap
            AppLanguage.TAMIL -> tamilMap
            AppLanguage.TELUGU -> teluguMap
            AppLanguage.BENGALI -> bengaliMap
            AppLanguage.PUNJABI -> punjabiMap
            AppLanguage.KANNADA -> kannadaMap
            AppLanguage.MALAYALAM -> malayalamMap
            AppLanguage.ODIA -> odiaMap
            AppLanguage.ASSAMESE -> assameseMap
            AppLanguage.URDU -> urduMap
            else -> null
        }
        return map?.get(key) ?: englishMap[key] ?: key
    }

    fun format(key: String, language: AppLanguage, vararg args: Any): String {
        val template = get(key, language)
        return try {
            String.format(language.getLocale(), template, *args)
        } catch (_: Exception) {
            template
        }
    }

